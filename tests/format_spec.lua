local ns = require("tests.helper").load("Logic/Format.lua")
local F = ns.Format

describe("Format", function()
  it("Money gold style rounds down", function()
    assert.are.equal("3,410g", F.Money(34101205, "gold"))
    assert.are.equal("0g", F.Money(0, "gold"))
  end)
  it("Money full style omits zero units", function()
    assert.are.equal("3,410g 12s 5c", F.Money(34101205, "full"))
    assert.are.equal("5s", F.Money(500, "full"))
  end)
  it("Duration formats h:mm:ss and m:ss", function()
    assert.are.equal("1:42:10", F.Duration(6130))
    assert.are.equal("4:05", F.Duration(245))
  end)
  it("Thousands inserts separators", function()
    assert.are.equal("1,234", F.Thousands(1234))
    assert.are.equal("123", F.Thousands(123))
    assert.are.equal("1,234,567", F.Thousands(1234567))
  end)
end)
