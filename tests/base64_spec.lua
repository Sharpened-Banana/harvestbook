local ns = require("tests.helper").load("Logic/Base64.lua")
local B = ns.Base64

describe("Base64", function()
  it("encodes RFC 4648 test vectors", function()
    assert.are.equal("", B.Encode(""))
    assert.are.equal("Zg==", B.Encode("f"))
    assert.are.equal("Zm8=", B.Encode("fo"))
    assert.are.equal("Zm9v", B.Encode("foo"))
    assert.are.equal("Zm9vYg==", B.Encode("foob"))
    assert.are.equal("Zm9vYmE=", B.Encode("fooba"))
    assert.are.equal("Zm9vYmFy", B.Encode("foobar"))
  end)
  it("decodes RFC 4648 test vectors", function()
    assert.are.equal("", B.Decode(""))
    assert.are.equal("f", B.Decode("Zg=="))
    assert.are.equal("fo", B.Decode("Zm8="))
    assert.are.equal("foobar", B.Decode("Zm9vYmFy"))
  end)
  it("round-trips all byte values", function()
    local bytes = {}
    for i = 0, 255 do bytes[#bytes + 1] = string.char(i) end
    local s = table.concat(bytes)
    for len = 0, 7 do
      local sub = s:sub(1, #s - len)
      assert.are.equal(sub, B.Decode(B.Encode(sub)))
    end
  end)
  it("ignores whitespace when decoding", function()
    assert.are.equal("foobar", B.Decode("  Zm9v\nYmFy \r\n"))
  end)
  it("rejects invalid input", function()
    assert.is_nil(B.Decode(nil))
    assert.is_nil(B.Decode("Zm9v!mFy"))
    assert.is_nil(B.Decode("Zm9"))
    assert.is_nil(B.Decode("Z==="))
    assert.is_nil(B.Decode("Zg=a"))
  end)
end)
