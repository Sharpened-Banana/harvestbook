local ns = require("tests.helper").load("Logic/GatherParse.lua")
local GP = ns.GatherParse

describe("GatherParse", function()
  it("ParseGUID reads GameObject id", function()
    local t, id = GP.ParseGUID("GameObject-0-1-2-3-5678-0000ABCDEF")
    assert.are.equal("GameObject", t)
    assert.are.equal(5678, id)
  end)
  it("ParseGUID reads Creature id", function()
    local t, id = GP.ParseGUID("Creature-0-1-2-3-12345-0000ABCDEF")
    assert.are.equal("Creature", t)
    assert.are.equal(12345, id)
  end)
  it("ParseGUID rejects malformed", function()
    assert.is_nil(GP.ParseGUID(nil))
    assert.is_nil(GP.ParseGUID(""))
    assert.is_nil(GP.ParseGUID(42))
    assert.is_nil(GP.ParseGUID("garbage"))
    assert.is_nil(GP.ParseGUID("Creature-0-1-2"))
    assert.is_nil(GP.ParseGUID("Creature-0-1-2-3-xyz-ABC"))
    assert.is_nil(GP.ParseGUID("Player-3676-0A1B2C3D"))
    assert.is_nil(GP.ParseGUID("Player-0-1-2-3-12345-ABC"))
  end)
  it("matcher matches unknown ID by name", function()
    local names = { [2575] = "Mining", [2366] = "Herb Gathering" }
    local match = GP.NewSpellMatcher(GP.KNOWN_SPELLS, function(id) return names[id] end)
    assert.are.equal("ore", match(2575, nil))
    assert.are.equal("ore", match(999999, "Mining"))
    assert.are.equal("herb", match(999998, "Herb Gathering"))
    assert.is_nil(match(999999, "Fishing"))
    assert.is_nil(match(999999, ""))
    assert.is_nil(match(999999, nil))
  end)
  it("matcher tolerates nil and throwing nameOf", function()
    local match = GP.NewSpellMatcher({ [1] = "ore", [2] = "herb" }, function(id)
      if id == 2 then error("boom") end
      return nil
    end)
    assert.are.equal("ore", match(1))
    assert.are.equal("herb", match(2))
    assert.is_nil(match(3, "x"))
  end)
  it("KNOWN_SPELLS has expected entries", function()
    assert.are.equal("ore", GP.KNOWN_SPELLS[2575])
    assert.are.equal("ore", GP.KNOWN_SPELLS[471013])
    assert.are.equal("herb", GP.KNOWN_SPELLS[2366])
    assert.are.equal("skin", GP.KNOWN_SPELLS[8613])
  end)
  it("PatternFromFormat extracts link and count", function()
    local pat, order = GP.PatternFromFormat("You receive loot: %sx%d.")
    assert.are.same({ 1, 2 }, order)
    local link, count = ("You receive loot: [Copper Ore]x3."):match(pat)
    assert.are.equal("[Copper Ore]", link)
    assert.are.equal("3", count)
    assert.is_nil(("You receive loot: [Copper Ore]x3!"):match(pat))
  end)
  it("PatternFromFormat escapes magic characters", function()
    local pat = GP.PatternFromFormat("(%s) +%d 100%% [x]")
    assert.are.equal("a", ("(a) +5 100% [x]"):match(pat))
  end)
  it("PatternFromFormat handles positional forms", function()
    local pat, order = GP.PatternFromFormat("%2$dx %1$s received.")
    assert.are.same({ 2, 1 }, order)
    local a, b = ("4x [Silverleaf] received."):match(pat)
    assert.are.equal("4", a)
    assert.are.equal("[Silverleaf]", b)
  end)
end)
